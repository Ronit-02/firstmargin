test('profile published writing retains identity through loading, failure, retry, and empty state', async ({ page }) => {
  const reads = await mockAccount(page)
  let release
  const held = new Promise(resolve => { release = resolve })
  let failing = true
  await page.route('**/api/writer/writer', async route => {
    await held
    return route.fulfill(failing ? { status: 500, json: { message: 'Unavailable' } } : { json: { data: { posts: [] } } })
  })
  await page.goto('/profile')
  await expect(page.getByRole('heading', { name: 'Writer', exact: true })).toBeVisible()
  await expect(page.getByRole('status', { name: 'Loading published writing' })).toBeVisible()
  release()
  const writing = page.getByRole('region', { name: 'Your published writing' })
  await expect(writing.getByRole('alert')).toContainText('Published writing could not be loaded.')
  await expect(page.getByRole('button', { name: 'Edit profile', exact: true })).toBeVisible()
  failing = false
  await writing.getByRole('button', { name: 'Try again', exact: true }).click()
  await expect(writing.getByText('No published stories yet.')).toBeVisible()
  expect(reads).not.toContain('/api/user/me/posts')
  expect(reads).not.toContain('/api/drafts')
})

