for (const width of [320, 1280]) {
  test(`history separates stories and shorts at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 800 })
    await page.addInitScript(theme => localStorage.setItem('ink-theme', theme), width === 320 ? 'light' : 'dark')
    await mockAccount(page)
    const story = { id, title: 'History story', lastReadAt: '2025-02-01', progress: 50, completed: false, author: { username: 'Writer' } }
    const short = { ...story, id: `${id.slice(0, -1)}2`, format: 'short', title: 'History short' }
    await page.route('**/api/v1/reading-history', route => route.fulfill({ json: { data: { continueReading: [short, story], history: [short, story] } } }))
    await page.goto('/saved?libraryTab=history&savedFormat=short&keep=yes')
    const tabs = page.getByRole('tablist', { name: 'History formats' })
    const stories = tabs.getByRole('tab', { name: 'Stories', exact: true })
    const shorts = tabs.getByRole('tab', { name: 'Shorts', exact: true })
    await expect(stories).toHaveAttribute('aria-selected', 'true')
    await expect(page.getByRole('heading', { name: 'History story', exact: true })).toHaveCount(1)
    await expect(page.getByRole('heading', { name: 'History short', exact: true })).toHaveCount(0)
    await stories.press('ArrowRight')
    await expect(shorts).toBeFocused()
    await expect(shorts).toHaveAttribute('aria-selected', 'true')
    await expect(page.getByRole('heading', { name: 'History short', exact: true })).toHaveCount(1)
    await expect(page.getByRole('heading', { name: 'History story', exact: true })).toHaveCount(0)
    await expect(page).toHaveURL(/historyFormat=short/)
    await page.reload()
    await expect(shorts).toHaveAttribute('aria-selected', 'true')
    await expect(page.getByRole('heading', { name: 'History short', exact: true })).toHaveCount(1)
    await page.getByRole('button', { name: /Filters/ }).click()
    await expect(page.getByRole('button', { name: 'Completed', exact: true })).toHaveCount(0)
    await expect(page.getByRole('button', { name: 'In progress', exact: true })).toHaveCount(0)
    await page.getByRole('button', { name: 'Close filters' }).click()
    await expect(shorts).toHaveAttribute('aria-selected', 'true')
    await expect(page.getByRole('heading', { name: 'History short', exact: true })).toHaveCount(1)
    await page.getByRole('tab', { name: 'Saved', exact: true }).click()
    await expect(page).toHaveURL(/savedFormat=short/)
    await page.getByRole('tab', { name: 'History', exact: true }).click()
    await expect(shorts).toHaveAttribute('aria-selected', 'true')
    await shorts.press('Home')
    await expect(stories).toBeFocused()
    await expect(page).not.toHaveURL(/historyFormat=/)
    await stories.press('End')
    await expect(shorts).toBeFocused()
    await expect(page.getByRole('main')).toHaveCount(1)
    expect(await page.getByRole('main').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
    await page.goto('/history?historyFormat=short')
    await expect(shorts).toHaveAttribute('aria-selected', 'true')
    await expect(page.getByRole('heading', { name: 'History story', exact: true })).toHaveCount(0)
    await page.screenshot({ path: `node_modules/.cache/account-groups/history-formats-${width}.png` })
  })
}
