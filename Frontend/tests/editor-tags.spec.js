import { test, expect } from './support/ui-test.js'

test('existing draft tags remain removable at the twenty-tag limit', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 820 })
  const tags = Array.from({ length: 20 }, (_, index) => `existing-${index}`)
  const saves = []
  await page.route(url => url.pathname.startsWith('/api/'), route => {
    const request = route.request()
    const path = new URL(request.url()).pathname
    if (path === '/api/auth/refresh-token') return route.fulfill({ json: { accessToken: 'test', user: 'Writer', email: 'writer@example.test', role: 'regular' } })
    if (path === '/api/drafts/full-tags' && request.method() === 'GET') return route.fulfill({ json: { data: { title: 'Existing tags', blocks: [{ id: 'first', type: 'text', content: 'Saved content' }], tags, format: 'short', version: 1 } } })
    if (path.startsWith('/api/drafts') && request.method() === 'PUT') { saves.push(request.postDataJSON()); return route.fulfill({ json: { data: { id: 'full-tags', version: saves.length + 1 } } }) }
    if (path === '/api/v1/me/entitlements') return route.fulfill({ json: { data: { capabilities: [] } } })
    return route.fulfill({ json: { data: [], meta: { unreadCount: 0, nextCursor: null } } })
  })
  await page.goto('/studio?draft=full-tags')
  await page.getByRole('button', { name: 'Publish', exact: true }).click()
  const field = page.getByRole('combobox', { name: 'Add a tag', exact: true })
  await expect(field).toBeDisabled()
  await expect(page.getByRole('button', { name: /^Remove existing-\d+ tag$/ })).toHaveCount(20)
  await page.getByRole('button', { name: 'Remove existing-0 tag' }).click()
  await expect(field).toBeEnabled()
  await field.fill('New choice')
  await page.getByRole('button', { name: 'Add', exact: true }).click()
  await expect(field).toBeDisabled()
  await expect.poll(() => saves.some(save => save.tags.length === 20 && save.tags.includes('new choice') && !save.tags.includes('existing-0'))).toBe(true)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
});

for (const width of [320, 1280]) {
  test(`tag selection, creation, recovery and content insertion at ${width}px`, async ({ page }, testInfo) => {
    await page.setViewportSize({ width, height: 820 })
    await page.addInitScript(theme => localStorage.setItem('ink-theme', theme), width === 320 ? 'light' : 'dark')
    const saves = []
    let failTags = false
    await page.route(url => url.pathname.startsWith('/api/'), route => {
      const request = route.request()
      const url = new URL(request.url())
      if (url.pathname === '/api/auth/refresh-token') return route.fulfill({ json: { accessToken: 'test', user: 'Writer', email: 'writer@example.test', role: 'regular' } })
      if (url.pathname === '/api/v1/tags') {
        if (failTags) return route.fulfill({ status: 500, json: { message: 'Unavailable' } })
        const options = [{ value: 'technology', label: 'Technology' }, { value: 'science', label: 'Science' }].filter(option => option.value.includes(url.searchParams.get('q') || ''))
        return route.fulfill({ json: { data: options } })
      }
      if (url.pathname.startsWith('/api/drafts') && ['POST', 'PUT'].includes(request.method())) { saves.push(request.postDataJSON()); return route.fulfill({ json: { data: { id: 'tags-draft', version: saves.length } } }) }
      if (url.pathname === '/api/v1/me/entitlements') return route.fulfill({ json: { data: { capabilities: [] } } })
      return route.fulfill({ json: { data: [], meta: { unreadCount: 0 } } })
    })
    await page.goto('/studio?new=article')
    await page.getByRole('textbox', { name: 'Story title', exact: true }).fill('Tag choices')
    await page.getByRole('textbox', { name: 'Paragraph block', exact: true }).fill('Testing tag choices in the publishing dialog.')
    await page.getByRole('button', { name: 'Publish', exact: true }).click()
    const field = page.getByRole('combobox', { name: 'Add a tag', exact: true })
    await expect(page.getByRole('button', { name: '+ Add cover image' })).toBeVisible()
    await expect(field).toBeVisible()
    await field.focus()
    await expect(page.getByRole('option', { name: 'Technology', exact: true })).toBeVisible()
    await field.press('ArrowDown')
    await expect(page.getByRole('option', { name: 'Science', exact: true })).toHaveAttribute('aria-selected', 'true')
    await field.press('ArrowUp')
    await field.press('Enter')
    await expect(page.getByRole('button', { name: 'Remove technology tag' })).toBeVisible()
    await expect(field).toBeFocused()
    await expect(field).toHaveAttribute('aria-expanded', 'false')
    await field.click()
    await expect(page.getByRole('option', { name: 'Science', exact: true })).toBeVisible()
    await field.press('Enter')
    await page.getByRole('button', { name: 'Remove science tag' }).click()
    await field.fill(' TECHNOLOGY ')
    await expect(page.getByRole('button', { name: 'Add', exact: true })).toBeDisabled()
    await field.press('Enter')
    await expect(page.getByRole('button', { name: 'Remove technology tag' })).toHaveCount(1)
    await field.fill('My new idea')
    await page.getByRole('option', { name: 'Add new tag “my new idea”', exact: true }).click()
    await expect.poll(() => saves.some(save => save.tags.includes('technology') && save.tags.includes('my new idea'))).toBe(true)
    await page.getByRole('button', { name: 'Remove technology tag' }).click()
    await expect(page.getByRole('button', { name: 'Remove technology tag' })).toHaveCount(0)
    failTags = true
    await field.fill('unavailable choice')
    await expect(page.getByRole('alert').filter({ hasText: 'Tag suggestions could not load' })).toBeVisible()
    await page.getByRole('option', { name: 'Add new tag “unavailable choice”' }).click()
    await expect(page.getByRole('button', { name: 'Remove unavailable choice tag' })).toBeVisible()
    await field.fill('retry choice')
    await expect(page.getByRole('button', { name: 'Retry tags' })).toBeVisible()
    failTags = false
    await page.getByRole('button', { name: 'Retry tags' }).focus()
    await page.getByRole('button', { name: 'Retry tags' }).press('Enter')
    await expect(page.getByRole('alert').filter({ hasText: 'Tag suggestions could not load' })).toHaveCount(0)
    await field.focus()
    await field.press('Escape')
    await expect(field).toBeFocused()
    await expect(field).toHaveAttribute('aria-expanded', 'false')
    await page.getByRole('button', { name: 'Close publishing options' }).click()
    const paragraph = page.getByRole('textbox', { name: 'Paragraph block', exact: true })
    await paragraph.fill('Original text stays intact')
    if (width < 1024) {
      const insert = page.getByRole('button', { name: 'Add block after this block', exact: true }).first()
      await insert.click()
      await page.getByRole('dialog', { name: 'Insert block', exact: true }).getByRole('button', { name: 'Heading 2', exact: true }).click()
      await expect(page.getByRole('textbox', { name: 'h2 block', exact: true })).toBeFocused()
      await page.getByRole('textbox', { name: 'h2 block', exact: true }).fill('A heading')
      const nextInsert = page.getByRole('button', { name: 'Add block after this block', exact: true }).last()
      await nextInsert.click()
      await page.keyboard.press('Escape')
      await expect(nextInsert).toBeFocused()
    } else {
      await expect(page.getByRole('button', { name: 'Add block after this block', exact: true })).toBeVisible()
      await paragraph.focus()
      await paragraph.press('End')
      await paragraph.press('Enter')
      const newParagraph = page.getByRole('textbox', { name: 'Paragraph block', exact: true }).last()
      await newParagraph.fill('/')
      await expect(page.getByRole('option', { name: 'Insert Heading 2', exact: true })).toBeVisible()
      await page.getByRole('option', { name: 'Insert Heading 2', exact: true }).click()
      await expect(page.getByRole('textbox', { name: 'h2 block', exact: true })).toBeFocused()
      await page.getByRole('textbox', { name: 'h2 block', exact: true }).fill('A heading')
    }
    await expect(paragraph).toHaveText('Original text stays intact')
    await expect(page.getByRole('listbox', { name: 'Insert block' })).toHaveCount(0)
    await page.getByRole('button', { name: 'Publish', exact: true }).click()
    const reopenedField = page.getByRole('combobox', { name: 'Add a tag', exact: true })
    await reopenedField.fill('one,two')
    await expect(page.getByRole('button', { name: 'Add', exact: true })).toBeDisabled()
    await reopenedField.press('Escape')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.locator('#main-content').evaluate(element => { element.scrollTop = 0 })
    await page.screenshot({ path: testInfo.outputPath('write-page.png'), fullPage: true })
  })
}
